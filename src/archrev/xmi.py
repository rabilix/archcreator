"""XMI 2.1 export of the as-built model for Enterprise Architect 16.

The export is a self-contained package `<Module> (as-built)` meant to be imported next to the design model (or into a
copy of it), never over it:

    <Module> (as-built)
      BlackBox    Component <Module> «as-built» with run info as tagged values; one diagram
      Interfaces  provided functions and globals as Interfaces «Function» / «Variable» (one feature each)
      Context     one package per other module: a Component (stereotype = archrev module kind) and the
                  Interfaces of the symbols the target uses from it
      Signals     one Interface «Signal» per signal-pool signal the target touches (Usage stereotype = access)

Connectors: Realization target -> provided Interface; Usage target -> required Interface and other -> provided
Interface (stereotype = dependency kind, evidence in the notes); one Dependency «as-built» per other module and
direction, with the kinds counted. Includes, macros and enum constants used across modules appear only there.

Layout follows the design model (BlackBox, Interfaces, «Function»). Types and signatures are not exported: the model
does not carry them. Every id is EA style (EAID_/EAPK_ + UUIDv5) and every key contains the target module, so a
re-import of the same module replaces its previous as-built package and exports of different modules never share an
element. No timestamps: identical models give identical files.
"""

from collections import Counter, defaultdict
from xml.sax.saxutils import escape

from .canonical import guid

XMI_TARGET = "ea16"
EXPORTER_VERSION = "6.5"  # what EA 16 writes into its own XMI 2.1 exports
TAG_MAX = 255  # EA stores longer tagged values as memos; keep tags short and put lists into the notes

_FUNCTION_KINDS = {"call", "fn_address"}
_VARIABLE_KINDS = {"global_read", "global_write", "global_addr"}
_NATURE = {"call": "Function", "fn_address": "Function", "global_read": "Variable", "global_write": "Variable",
           "global_addr": "Variable", "macro_use": "Macro", "enum_use": "EnumConstant"}

# Diagram layout (EA units). Columns: users of the target, provided interfaces, target, used modules.
_W, _H, _GAP, _ROWS = 220, 60, 30, 20
_COL_X = (40, 320, 600, 880)


def _xid(prefix: str, key: str) -> str:
    return f"{prefix}_{guid('xmi:' + key).upper().replace('-', '_')}"


def _attr(value) -> str:
    return escape(str(value), {'"': "&quot;", "\n": "&#xA;", "\r": "", "\t": "&#x9;"})


def _evidence_lines(evidence: list[dict]) -> list[str]:
    lines = []
    for e in evidence:
        line = f"{e['file']}:{e['line']}"
        if e.get("function"):
            line += f" in {e['function']}"
        if e.get("via_macro"):
            line += f" via macro {e['via_macro']}"
        lines.append(line)
    return lines


class _Builder:
    def __init__(self) -> None:
        self.packages: dict[str, dict] = {}
        self.elements: dict[str, dict] = {}
        self.connectors: list[dict] = []

    def package(self, key: str, name: str, parent: str | None, doc: str = "") -> str:
        pid = _xid("EAPK", key)
        if pid not in self.packages:
            self.packages[pid] = {"id": pid, "name": name, "parent": parent, "doc": doc, "children": [],
                                  "elements": [], "connectors": []}
            if parent:
                self.packages[parent]["children"].append(pid)
        return pid

    def element(self, key: str, uml_type: str, name: str, pkg: str, stereotype: str | None, doc: str = "",
                tags: dict | None = None, feature: str | None = None) -> str:
        eid = _xid("EAID", key)
        if eid not in self.elements:
            self.elements[eid] = {"id": eid, "type": uml_type, "name": name, "pkg": pkg, "stereotype": stereotype,
                                  "doc": doc, "tags": tags or {}, "feature": feature}
            self.packages[pkg]["elements"].append(eid)
        return eid

    def connector(self, key: str, uml_type: str, client: str, supplier: str, stereotype: str | None,
                  doc: str = "", tags: dict | None = None) -> None:
        c = {"id": _xid("EAID", key), "type": uml_type, "client": client, "supplier": supplier,
             "stereotype": stereotype, "doc": doc, "tags": tags or {}}
        self.connectors.append(c)
        self.packages[self.elements[client]["pkg"]]["connectors"].append(c)


def build(model: dict, manifest: dict) -> _Builder:
    b = _Builder()
    target = model["target"]
    tid = target["id"]
    name = target["name"]
    modules = {m["id"]: m for m in model["modules"]}

    root = b.package(f"pkg:{tid}", f"{name} (as-built)", None,
                     doc=f"Generated by archrev {manifest['tool_version']} from commit {manifest['target_commit']}"
                         f"{' (uncommitted changes)' if manifest['target_dirty'] else ''}. "
                         "As-built view of the code, not design. Do not edit; re-import replaces it.")
    blackbox = b.package(f"pkg:{tid}:BlackBox", "BlackBox", root)
    interfaces = b.package(f"pkg:{tid}:Interfaces", "Interfaces", root)
    context = b.package(f"pkg:{tid}:Context", "Context", root)

    run_tags = {"archrev_version": manifest["tool_version"], "target_commit": manifest["target_commit"],
                "target_dirty": str(manifest["target_dirty"]).lower(), "profile": manifest["profile_name"],
                "parse_coverage": manifest["parse_coverage"]["ratio"], "module_kind": target["kind"]}
    comp = b.element(f"comp:{tid}", "Component", name, blackbox, "as-built",
                     doc="Files:\n" + "\n".join(target["files"]), tags=run_tags)

    provided: dict[str, str] = {}
    for kind, stereo, feature in (("functions", "Function", "operation"), ("globals", "Variable", "attribute")):
        for f in model["provided_interface"][kind]:
            where = [f"defined at {f['defined_at']}"] if f["defined_at"] else []
            where += [f"declared in {d}" for d in f["declared_in"]]
            iid = b.element(f"prov:{tid}:{f['usr']}", "Interface", f["name"], interfaces, stereo,
                            doc="\n".join(where), tags={"usr": f["usr"]}, feature=feature)
            provided[f["usr"]] = iid
            b.connector(f"real:{tid}:{f['usr']}", "Realization", comp, iid, None)

    others: dict[str, str] = {}
    signals_pkg: list[str] = []

    def other(module_id: str) -> str:
        if module_id not in others and module_id.startswith("signal:"):
            if not signals_pkg:
                signals_pkg.append(b.package(f"pkg:{tid}:Signals", "Signals", root))
            m = modules[module_id]
            others[module_id] = b.element(f"ctx:{tid}:{module_id}", "Interface", m["name"], signals_pkg[0], "Signal",
                                          doc="Signal exchanged through the signal pool.", tags={"signal": m["name"]})
        if module_id not in others:
            m = modules[module_id]
            pkg = b.package(f"pkg:{tid}:ctx:{module_id}", m["name"], context)
            # Keyed by target too: the same module is a context element in every other module's export, and EA
            # would move one shared element between packages instead of keeping each export self-contained.
            others[module_id] = b.element(f"ctx:{tid}:{module_id}", "Component", m["name"], pkg, m["kind"],
                                          doc="Files:\n" + "\n".join(m["files"]), tags={"module_id": module_id})
        return others[module_id]

    summary: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for e in model["dependencies"]["outgoing"]:
        summary[("out", e["to"])].append(e)
        if e["kind"] == "include":
            continue
        ocomp = other(e["to"])
        if e["kind"].startswith("signal_"):
            _usage(b, tid, e, comp, ocomp)  # the signal interface itself is the supplier
            continue
        nature = _NATURE[e["kind"]]
        feature = "operation" if e["kind"] in _FUNCTION_KINDS else "attribute" if e["kind"] in _VARIABLE_KINDS else None
        iid = b.element(f"req:{tid}:{e['to']}:{nature}:{e['usr'] or e['symbol']}", "Interface", e["symbol"],
                        b.elements[ocomp]["pkg"], nature, tags={"usr": e["usr"]} if e["usr"] else {}, feature=feature)
        _usage(b, tid, e, comp, iid)
    for e in model["dependencies"]["incoming"]:
        summary[("in", e["from"])].append(e)
        if e["usr"] in provided:
            _usage(b, tid, e, other(e["from"]), provided[e["usr"]])

    for (direction, module_id), edges in sorted(summary.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        ocomp = other(module_id)
        client, supplier = (comp, ocomp) if direction == "out" else (ocomp, comp)
        counts = Counter(e["kind"] for e in edges)
        doc = "\n".join(f"{e['kind']} {e['symbol']} ({len(e['evidence'])} uses)" for e in edges)
        b.connector(f"dep:{direction}:{tid}:{module_id}", "Dependency", client, supplier, "as-built", doc=doc,
                    tags={"kinds": "; ".join(f"{k}={n}" for k, n in sorted(counts.items())),
                          "evidence_count": sum(len(e["evidence"]) for e in edges)})
    return b


def _usage(b: _Builder, tid: str, edge: dict, client: str, supplier: str) -> None:
    lines = _evidence_lines(edge["evidence"])
    macros = sorted({e["via_macro"] for e in edge["evidence"] if e.get("via_macro")})
    tags = {"evidence_count": len(lines), "first_evidence": lines[0] if lines else ""}
    if macros and len("; ".join(macros)) <= TAG_MAX:
        tags["via_macros"] = "; ".join(macros)
    # An edge id is the same seen from either end (A's outgoing edge to B is B's incoming edge from A).
    b.connector(f"use:{tid}:{edge['id']}", "Usage", client, supplier, edge["kind"], doc="\n".join(lines), tags=tags)


def render(model: dict, manifest: dict) -> str:
    """The EA 16 XMI 2.1 document for one module model and its run manifest."""
    b = build(model, manifest)
    root = next(p for p in b.packages.values() if p["parent"] is None)
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<xmi:XMI xmi:version="2.1" xmlns:uml="http://schema.omg.org/spec/UML/2.1" '
           'xmlns:xmi="http://schema.omg.org/spec/XMI/2.1" '
           'xmlns:thecustomprofile="http://www.sparxsystems.com/profiles/thecustomprofile/1.0">',
           f'\t<xmi:Documentation exporter="Enterprise Architect" exporterVersion="{EXPORTER_VERSION}" '
           f'exporterID="archrev"/>',
           '\t<uml:Model xmi:type="uml:Model" name="EA_Model" visibility="public">']
    _uml_package(b, root["id"], 2, out)
    out.append("\t</uml:Model>")
    for e in b.elements.values():
        if e["stereotype"]:
            out.append(f'\t<thecustomprofile:{e["stereotype"]} base_{e["type"]}="{e["id"]}"/>')
    for c in b.connectors:
        if c["stereotype"]:
            out.append(f'\t<thecustomprofile:{c["stereotype"]} base_{c["type"]}="{c["id"]}"/>')
    out.append('\t<xmi:Extension extender="Enterprise Architect" extenderID="6.5">')
    _ext_elements(b, out)
    _ext_connectors(b, out)
    _ext_diagram(b, model, out)
    out += ["\t</xmi:Extension>", "</xmi:XMI>", ""]
    return "\n".join(out)


def _uml_package(b: _Builder, pid: str, depth: int, out: list[str]) -> None:
    p = b.packages[pid]
    ind = "\t" * depth
    out.append(f'{ind}<packagedElement xmi:type="uml:Package" xmi:id="{pid}" name="{_attr(p["name"])}" '
               f'visibility="public">')
    for child in p["children"]:
        _uml_package(b, child, depth + 1, out)
    for eid in p["elements"]:
        e = b.elements[eid]
        head = f'{ind}\t<packagedElement xmi:type="uml:{e["type"]}" xmi:id="{eid}" name="{_attr(e["name"])}" ' \
               f'visibility="public"'
        fid = _xid("EAID", "feature:" + eid)
        if e["feature"] == "operation":
            out += [head + ">", f'{ind}\t\t<ownedOperation xmi:id="{fid}" name="{_attr(e["name"])}" '
                                f'visibility="public" concurrency="sequential"/>', f"{ind}\t</packagedElement>"]
        elif e["feature"] == "attribute":
            out += [head + ">", f'{ind}\t\t<ownedAttribute xmi:type="uml:Property" xmi:id="{fid}" '
                                f'name="{_attr(e["name"])}" visibility="public" isStatic="false" isReadOnly="false"/>',
                    f"{ind}\t</packagedElement>"]
        else:
            out.append(head + "/>")
    for c in p["connectors"]:
        out.append(f'{ind}\t<packagedElement xmi:type="uml:{c["type"]}" xmi:id="{c["id"]}" visibility="public" '
                   f'supplier="{c["supplier"]}" client="{c["client"]}"/>')
    out.append(f"{ind}</packagedElement>")


def _tags(owner: str, tags: dict, ind: str, out: list[str]) -> None:
    if not tags:
        return
    out.append(f"{ind}<tags>")
    for name, value in sorted(tags.items()):
        out.append(f'{ind}\t<tag xmi:id="{_xid("EAID", f"tag:{owner}:{name}")}" name="{_attr(name)}" '
                   f'value="{_attr(str(value)[:TAG_MAX])}" modelElement="{owner}"/>')
    out.append(f"{ind}</tags>")


def _ext_elements(b: _Builder, out: list[str]) -> None:
    out.append("\t\t<elements>")
    for p in b.packages.values():
        eid = p["id"].replace("EAPK_", "EAID_", 1)
        parent = f' package="{p["parent"]}"' if p["parent"] else ""
        out += [f'\t\t\t<element xmi:idref="{p["id"]}" xmi:type="uml:Package" name="{_attr(p["name"])}" '
                f'scope="public">',
                f'\t\t\t\t<model package2="{eid}"{parent} ea_eleType="package"/>',
                f'\t\t\t\t<properties documentation="{_attr(p["doc"])}" isSpecification="false" sType="Package" '
                f'nType="0" scope="public"/>',
                "\t\t\t</element>"]
    for e in b.elements.values():
        stereo = f' stereotype="{_attr(e["stereotype"])}"' if e["stereotype"] else ""
        out += [f'\t\t\t<element xmi:idref="{e["id"]}" xmi:type="uml:{e["type"]}" name="{_attr(e["name"])}" '
                f'scope="public">',
                f'\t\t\t\t<model package="{e["pkg"]}" ea_eleType="element"/>',
                f'\t\t\t\t<properties documentation="{_attr(e["doc"])}" isSpecification="false" '
                f'sType="{e["type"]}" nType="0" scope="public"{stereo}/>']
        _tags(e["id"], e["tags"], "\t\t\t\t", out)
        out.append("\t\t\t</element>")
    out.append("\t\t</elements>")


def _ext_connectors(b: _Builder, out: list[str]) -> None:
    out.append("\t\t<connectors>")
    for c in b.connectors:
        src, dst = b.elements[c["client"]], b.elements[c["supplier"]]
        stereo = f' stereotype="{_attr(c["stereotype"])}"' if c["stereotype"] else ""
        out += [f'\t\t\t<connector xmi:idref="{c["id"]}">',
                f'\t\t\t\t<source xmi:idref="{src["id"]}"><model type="{src["type"]}" name="{_attr(src["name"])}"/>'
                f"</source>",
                f'\t\t\t\t<target xmi:idref="{dst["id"]}"><model type="{dst["type"]}" name="{_attr(dst["name"])}"/>'
                f"</target>",
                f'\t\t\t\t<properties ea_type="{c["type"]}" direction="Source -&gt; Destination"{stereo}/>',
                f'\t\t\t\t<documentation value="{_attr(c["doc"])}"/>']
        _tags(c["id"], c["tags"], "\t\t\t\t", out)
        out.append("\t\t\t</connector>")
    out.append("\t\t</connectors>")


def _ext_diagram(b: _Builder, model: dict, out: list[str]) -> None:
    tid = model["target"]["id"]
    comp = _xid("EAID", f"comp:{tid}")
    blackbox = b.elements[comp]["pkg"]
    provided = [c["supplier"] for c in b.connectors if c["type"] == "Realization"]
    users, used = [], []
    for c in b.connectors:
        if c["type"] != "Dependency":
            continue
        if c["client"] == comp and c["supplier"] not in used:
            used.append(c["supplier"])
    for c in b.connectors:
        if c["type"] == "Dependency" and c["supplier"] == comp and c["client"] not in used and c["client"] not in users:
            users.append(c["client"])

    placed: list[tuple[str, int, int]] = []

    def column(ids: list[str], base: int, step: int) -> None:
        for i, eid in enumerate(ids):
            placed.append((eid, _COL_X[base] + (i // _ROWS) * step, 40 + (i % _ROWS) * (_H + _GAP)))

    # Long columns wrap away from the target: users to the left, used modules to the right.
    column(users, 0, -(_W + _GAP))
    for i, eid in enumerate(provided):
        placed.append((eid, _COL_X[1], 40 + i * (_H + _GAP)))
    placed.append((comp, _COL_X[2], 40))
    column(used, 3, _W + _GAP)
    shift = max(0, 40 - min(x for _, x, _ in placed))

    did = _xid("EAID", f"diagram:{tid}")
    out += ["\t\t<diagrams>", f'\t\t\t<diagram xmi:id="{did}">',
            f'\t\t\t\t<model package="{blackbox}" owner="{blackbox}"/>',
            f'\t\t\t\t<properties name="{_attr(model["target"]["name"])} (as-built)" type="Component"/>',
            "\t\t\t\t<elements>"]
    for seq, (eid, x, y) in enumerate(placed, 1):
        x += shift
        out.append(f'\t\t\t\t\t<element geometry="Left={x};Top={y};Right={x + _W};Bottom={y + _H};" '
                   f'subject="{eid}" seqno="{seq}"/>')
    out += ["\t\t\t\t</elements>", "\t\t\t</diagram>", "\t\t</diagrams>"]
